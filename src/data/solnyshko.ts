/**
 * Порядок разрешения равенства показаний: при равенстве баллов
 * назначается комплекс — комиссия не выбирает между методами,
 * когда может применить все.
 */
const QUIZ_TIE_ORDER: QuizProgram[] = ["complex", "second", "safety", "morning"];

/** Назначает программу по заполненным ответам; незаполненные пункты не учитываются. */
export function recommendQuizResult(answers: (string | null)[]): QuizResult {
  const scores: Record<QuizProgram, number> = {
    morning: 0,
    safety: 0,
    second: 0,
    complex: 0,
  };

  QUIZ_QUESTIONS.forEach((q, i) => {
    const option = q.options.find((o) => o.value === answers[i]);
    if (option) scores[option.program] += 1;
  });

  const key = QUIZ_TIE_ORDER.reduce((best, candidate) =>
    scores[candidate] > scores[best] ? candidate : best,
  );

  return QUIZ_RESULTS.find((r) => r.key === key) ?? QUIZ_RESULTS[0];
}
